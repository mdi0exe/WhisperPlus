#!/usr/bin/env python3
"""Harvest a published app folder into a WiX v5 fragment (.wxs).

Generates explicit Component/File pairs (Guid="*" for deterministic, patchable
components) and a single ComponentGroup "PublishFiles" referencing every component.
Run:  python harvest.py <publish-dir> <out.wxs>
"""
import os
import sys
import uuid


#: Id of the install root directory in installer/WhisperPlus.wxs.
ROOT_DIR_ID = "INSTALLDIR"


def slug_id(prefix: str, n: int) -> str:
    return f"{prefix}_{n:x}"


def main() -> None:
    publish_dir = os.path.normpath(sys.argv[1])
    out_path = sys.argv[2]
    # Absolute, forward-slash source prefix. WiX accepts forward slashes; this keeps
    # the fragment self-contained (no per-file preprocessor variable needed).
    prefix = publish_dir.replace("\\", "/")

    files: list[tuple[str, str, str, str]] = []  # (component_id, file_id, dir_id, rel_path)
    dir_ids: dict[str, str] = {}  # rel dir -> dir id
    dir_counter = 0
    file_counter = 0

    # Root install dir id must match the Directory the main .wxs declares for the install root,
    # which is WIXUI_INSTALLDIR (it is what the wizard's "Destination Folder" page edits). Using a
    # different id here produced a fragment whose DirectoryRef pointed at a directory that did not
    # exist, and the MSI build failed with an unresolved symbol.
    dir_ids["."] = ROOT_DIR_ID

    for root, _dirs, names in os.walk(publish_dir):
        rel_root = os.path.relpath(root, publish_dir)
        rel_root_norm = "." if rel_root == "." else rel_root.replace("\\", "/")
        # Ensure the directory for this rel_root has an id (root is already mapped).
        if rel_root_norm not in dir_ids:
            dir_counter += 1
            dir_ids[rel_root_norm] = slug_id("d", dir_counter)
        dir_id = dir_ids[rel_root_norm]

        for name in sorted(names):
            rel = os.path.join(rel_root, name) if rel_root != "." else name
            # Give the main executable a stable id so the product file can target it
            # for the Start Menu shortcut and "launch on finish" custom action.
            if rel_root == "." and name.lower() == "whisperplus.exe":
                cid, fid = "WhisperPlusExeComp", "WhisperPlusExe"
            else:
                file_counter += 1
                cid = slug_id("c", file_counter)
                fid = slug_id("f", file_counter)
            files.append((cid, fid, dir_id, rel.replace("\\", "/")))

    # Build a directory tree so each subdir Directory element is nested under its parent.
    # Collect ordered unique subdirs (excluding root).
    subdir_paths = [d for d in dir_ids if d != "."]
    # sort by depth then name for deterministic, parent-before-child nesting
    subdir_paths.sort(key=lambda p: (p.count("/"), p))

    # Map each subdir to its parent and child list.
    children: dict[str, list[str]] = {".": []}
    name_of: dict[str, str] = {}
    for d in subdir_paths:
        parent = "/".join(d.split("/")[:-1]) or "."
        children.setdefault(parent, []).append(d)
        name_of[d] = d.split("/")[-1]
        children.setdefault(d, [])

    lines: list[str] = []
    lines.append('<?xml version="1.0" encoding="UTF-8"?>')
    lines.append(
        '<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">'
    )
    lines.append("<!-- AUTO-GENERATED by harvest.py. Do not edit by hand. -->")
    lines.append("  <Fragment>")

    # Directory tree. Root dir (WIXUI_INSTALLDIR) is defined in the main file; here we
    # emit its children via DirectoryRef so nesting stays readable.
    def emit_dir(rel: str, indent: str) -> None:
        did = dir_ids[rel]
        nm = name_of[rel]
        lines.append(f'{indent}<Directory Id="{did}" Name="{nm}">')
        for child in children.get(rel, []):
            emit_dir(child, indent + "  ")
        lines.append(f"{indent}</Directory>")

    lines.append(f'    <DirectoryRef Id="{ROOT_DIR_ID}">')
    for child in children.get(".", []):
        emit_dir(child, "      ")
    lines.append("    </DirectoryRef>")

    # Components. Each File lives in the directory named by its Component Directory attr.
    for cid, fid, did, rel in files:
        source = f"{prefix}/{rel}"
        lines.append(f'    <Component Id="{cid}" Guid="*" Directory="{did}">')
        lines.append(f'      <File Id="{fid}" Source="{source}" KeyPath="yes" />')
        lines.append("    </Component>")

    # ComponentGroup referencing every component.
    lines.append('    <ComponentGroup Id="PublishFiles">')
    for cid, _fid, _did, _rel in files:
        lines.append(f'      <ComponentRef Id="{cid}" />')
    lines.append("    </ComponentGroup>")

    lines.append("  </Fragment>")
    lines.append("</Wix>")

    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")

    print(f"Harvested {len(files)} files, {len(subdir_paths)} subdirs -> {out_path}")


if __name__ == "__main__":
    main()
