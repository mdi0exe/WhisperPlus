#!/usr/bin/env python3
"""Bundle the WhisperPlus source tree into Markdown files that can be handed to a
code-reviewing model.

Every file is emitted verbatim inside a fenced block, preceded by its path and line
count, so a reader (human or model) can tell exactly where each fragment came from.
Build output (`bin`, `obj`), VCS metadata and the assistant's own scratch folders are
skipped.

Usage:
    python tools/bundle_source.py                 # write ./source-bundle
    python tools/bundle_source.py --out DIR       # write somewhere else
    python tools/bundle_source.py --no-split      # only the single-file bundle
"""

from __future__ import annotations

import argparse
import datetime as _dt
import os
import sys
from dataclasses import dataclass
from pathlib import Path

# --------------------------------------------------------------------------------------
# What goes in, and in which order. Each group becomes one part file.
# --------------------------------------------------------------------------------------

TEXT_EXTENSIONS = {
    ".cs", ".xaml", ".csproj", ".props", ".targets", ".sln", ".manifest",
    ".json", ".md", ".wxs", ".wxi", ".py", ".ps1", ".xml", ".config",
}

LANGUAGE_BY_EXTENSION = {
    ".cs": "csharp",
    ".xaml": "xml",
    ".xml": "xml",
    ".csproj": "xml",
    ".props": "xml",
    ".targets": "xml",
    ".wxs": "xml",
    ".wxi": "xml",
    ".config": "xml",
    ".manifest": "xml",
    ".json": "json",
    ".md": "markdown",
    ".py": "python",
    ".ps1": "powershell",
    ".sln": "text",
}

EXCLUDED_DIRS = {
    "bin", "obj", ".git", ".vs", ".idea", ".workbuddy-ai", ".claude",
    ".agents", ".continue", ".config", ".wix", "node_modules", "source-bundle",
}

EXCLUDED_FILES = {
    "skills-lock.json",          # tooling metadata, not app source
    "PublishFiles.wxs",          # generated by installer/harvest.py from the publish output
}

# (title, description, list of path prefixes relative to the repository root)
GROUPS: list[tuple[str, str, tuple[str, ...]]] = [
    (
        "Core",
        "Application shell, models, Win32 interop, helpers and the service layer "
        "(speech engines, language routing, layout fixer, tray, settings).",
        (
            "Directory.Build.props", "global.json", "WhisperPlus.sln",
            "src/WhisperPlus/App.xaml", "src/WhisperPlus/App.xaml.cs",
            "src/WhisperPlus/WhisperPlus.csproj", "src/WhisperPlus/app.manifest",
            "src/WhisperPlus/AssemblyInfo.cs",
            "src/WhisperPlus/Models", "src/WhisperPlus/Interop",
            "src/WhisperPlus/Helpers", "src/WhisperPlus/ViewModels",
            "src/WhisperPlus/Services",
        ),
    ),
    (
        "ScreenCapture",
        "Screenshot capture and annotation, ported from screen_forge: the overlay, "
        "the SkiaSharp scene/editor, the clipboard exporter and the hotkey hook.",
        ("src/WhisperPlus/ScreenCapture",),
    ),
    (
        "UI",
        "WPF views: the navigation shell, settings pages, floating widgets and the "
        "Aurora theme dictionaries.",
        ("src/WhisperPlus/Views", "src/WhisperPlus/Themes"),
    ),
    (
        "TestsAndPackaging",
        "Unit tests, the MSI packaging sources and the project README.",
        ("tests", "installer", "README.md"),
    ),
]


@dataclass
class SourceFile:
    path: Path            # absolute
    relative: str         # repository-relative, forward slashes
    text: str
    lines: int
    size: int


def is_text_candidate(path: Path) -> bool:
    if path.suffix.lower() not in TEXT_EXTENSIONS:
        return False
    if path.name in EXCLUDED_FILES:
        return False
    # Skip anything under an excluded directory (bin/obj/...), at any depth.
    return not any(part in EXCLUDED_DIRS for part in path.parts)


def read_source(path: Path, root: Path) -> SourceFile | None:
    try:
        raw = path.read_bytes()
    except OSError:
        return None
    if b"\x00" in raw[:4096]:        # binary masquerading as text
        return None
    try:
        text = raw.decode("utf-8-sig")
    except UnicodeDecodeError:
        text = raw.decode("utf-8", errors="replace")
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    return SourceFile(
        path=path,
        relative=path.relative_to(root).as_posix(),
        text=text,
        lines=text.count("\n") + (0 if text.endswith("\n") else 1),
        size=len(raw),
    )


def collect(root: Path, prefixes: tuple[str, ...]) -> list[SourceFile]:
    """Every text file under the given prefixes, in a stable, readable order."""
    found: dict[str, SourceFile] = {}
    for prefix in prefixes:
        target = root / prefix
        if target.is_file():
            entry = read_source(target, root)
            if entry:
                found[entry.relative] = entry
            continue
        if not target.is_dir():
            continue
        for path in sorted(target.rglob("*")):
            if not path.is_file() or not is_text_candidate(path):
                continue
            entry = read_source(path, root)
            if entry:
                found[entry.relative] = entry
    return [found[key] for key in sorted(found)]


def fence_for(text: str) -> str:
    """A fence longer than any backtick run inside the file, so nesting never breaks."""
    longest = 0
    run = 0
    for ch in text:
        if ch == "`":
            run += 1
            longest = max(longest, run)
        else:
            run = 0
    return "`" * max(3, longest + 1)


def render_file(entry: SourceFile, number: int) -> str:
    language = LANGUAGE_BY_EXTENSION.get(entry.path.suffix.lower(), "text")
    fence = fence_for(entry.text)
    body = entry.text if entry.text.endswith("\n") else entry.text + "\n"
    return (
        f"### {number}. `{entry.relative}`  \n"
        f"*{entry.lines} lines · {entry.size / 1024:.1f} KB*\n\n"
        f"{fence}{language}\n{body}{fence}\n\n"
    )


def file_tree(root: Path, files: list[SourceFile]) -> str:
    """A compact directory tree of just the files that are in the bundle."""
    lines: list[str] = []
    previous: list[str] = []
    for entry in files:
        parts = entry.relative.split("/")
        for depth, part in enumerate(parts[:-1]):
            if depth >= len(previous) or previous[depth] != part:
                lines.append("    " * depth + part + "/")
                previous = previous[:depth] + [part]
        lines.append("    " * (len(parts) - 1) + parts[-1])
        previous = parts[:-1]
    return "\n".join(lines)


def header(title: str, root: Path, files: list[SourceFile], stamp: str, note: str) -> str:
    total_lines = sum(f.lines for f in files)
    total_kb = sum(f.size for f in files) / 1024
    return (
        f"# {title}\n\n"
        f"**Project:** WhisperPlus — offline speech-to-text, floating audio recorder, "
        f"Persian ⇄ English layout fixer, and screenshot annotation, for Windows.\n"
        f"**Stack:** .NET 10 · WPF · WPF-UI (Fluent/Mica) · NAudio · Whisper.net · Vosk · "
        f"sherpa-onnx · SkiaSharp · Serilog\n"
        f"**Repository root:** `{root.as_posix()}`  \n"
        f"**Generated:** {stamp}  \n"
        f"**Contents:** {len(files)} files · {total_lines:,} lines · {total_kb:,.0f} KB\n\n"
        f"{note}\n"
        f"---\n\n"
    )


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(content)
    print(f"  {path.name:<34} {len(content.encode('utf-8')) / 1024:8.1f} KB")


def build_part(root: Path, stamp: str, title: str, description: str,
               files: list[SourceFile]) -> str:
    note = (
        f"{description}\n\n"
        "Every file below is reproduced verbatim. The path above each block is relative to "
        "the repository root, so a finding can be quoted as `path:line`.\n"
    )
    out = [header(f"WhisperPlus source — {title}", root, files, stamp, note)]
    out.append("## Files in this part\n\n")
    out.append("| # | File | Lines |\n|---|------|-------|\n")
    for index, entry in enumerate(files, start=1):
        out.append(f"| {index} | `{entry.relative}` | {entry.lines} |\n")
    out.append("\n---\n\n## Source\n\n")
    for index, entry in enumerate(files, start=1):
        out.append(render_file(entry, index))
    return "".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default=Path(__file__).resolve().parent.parent,
                        type=Path, help="repository root (default: the script's parent)")
    parser.add_argument("--out", default=None, type=Path,
                        help="output directory (default: <root>/source-bundle)")
    parser.add_argument("--no-split", action="store_true",
                        help="only write the single-file bundle")
    args = parser.parse_args()

    root: Path = args.root.resolve()
    out_dir: Path = (args.out or (root / "source-bundle")).resolve()
    stamp = _dt.datetime.now().strftime("%Y-%m-%d %H:%M")

    groups = [(name, desc, collect(root, prefixes)) for name, desc, prefixes in GROUPS]
    groups = [g for g in groups if g[2]]
    if not groups:
        print("No source files found.", file=sys.stderr)
        return 1

    everything: list[SourceFile] = []
    seen: set[str] = set()
    for _, _, files in groups:
        for entry in files:
            if entry.relative not in seen:
                seen.add(entry.relative)
                everything.append(entry)
    everything.sort(key=lambda f: f.relative)

    print(f"Bundling {len(everything)} files from {root}")

    if not args.no_split:
        for index, (name, description, files) in enumerate(groups, start=1):
            content = build_part(root, stamp, name, description, files)
            write(out_dir / f"{index:02d}-{name}.md", content)

    # ---- single-file bundle -------------------------------------------------------
    note = (
        "This is the complete source of the application in one document: every `.cs`, `.xaml`, "
        "`.csproj`, test, packaging file and the README. Build output, VCS metadata, editor state "
        "and the generated WiX file list are excluded.\n\n"
        "**How to use it for a review:** each file starts with `### <n>. <path>` and its line "
        "count; the path is relative to the repository root, so findings can be quoted as "
        "`path:line`. The index below lists everything in reading order.\n\n"
        "**Suggested reading order** (the parts a review usually starts from):\n\n"
        "1. `README.md` — what the app does, feature by feature.\n"
        "2. `src/WhisperPlus/App.xaml.cs` — DI wiring, hotkey routing, startup.\n"
        "3. `src/WhisperPlus/Services/LayoutFixService.cs` + `TextSelectionService.cs` + "
        "`TextInjector.cs` — the Ctrl+Space cycle (clipboard-free path and clipboard path).\n"
        "4. `src/WhisperPlus/Services/PersianEnglishLayoutConverter.cs` + "
        "`PersianKeyboardLayouts.cs` — the two Persian layouts and the key tables.\n"
        "5. `src/WhisperPlus/ScreenCapture/ScreenshotService.cs` + "
        "`CaptureOverlayWindow.xaml.cs` + `ScreenshotHotkeyHook.cs` — screenshot feature.\n"
        "6. `src/WhisperPlus/Services/StreamingDictationSession.cs` + `LanguageRouter.cs` — "
        "language detection, routing and live transcription.\n"
    )
    parts = [header("WhisperPlus — complete source bundle", root, everything, stamp, note)]

    parts.append("## Project layout\n\n```text\n")
    parts.append(file_tree(root, everything))
    parts.append("\n```\n\n## Index\n\n| # | File | Lines |\n|---|------|-------|\n")
    for index, entry in enumerate(everything, start=1):
        parts.append(f"| {index} | `{entry.relative}` | {entry.lines} |\n")
    parts.append("\n---\n\n")

    # Group headings keep the single file navigable, even though the index is flat.
    group_of: dict[str, str] = {}
    for name, _, files in groups:
        for entry in files:
            group_of.setdefault(entry.relative, name)

    current = None
    for index, entry in enumerate(everything, start=1):
        group = group_of.get(entry.relative, "Other")
        if group != current:
            current = group
            parts.append(f"\n## Part — {group}\n\n")
        parts.append(render_file(entry, index))

    write(out_dir / "whisperplus-full-source.md", "".join(parts))

    total_lines = sum(f.lines for f in everything)
    print(f"\nDone: {len(everything)} files, {total_lines:,} lines -> {out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
